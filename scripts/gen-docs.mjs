// Builds the overlay reference from the live catalog so docs never drift from the app.
//   npm run docs   → updates the table in README.md and writes docs/OVERLAYS.md
// Needs ./data (run `npm run fetch` first): some items are computed from data.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { GROUPS, ITEMS, UNAVAILABLE, dataUrl } = await import(path.join(ROOT, 'public/js/catalog.js'));

const bars = JSON.parse(readFileSync(path.join(ROOT, 'data/btc.json'), 'utf8'));
const cache = {};
const ctx = { bars, get: (k) => (cache[k] ??= JSON.parse(readFileSync(path.join(ROOT, dataUrl(k)), 'utf8'))) };

const NEED_SRC = (k) => k.startsWith('fred:') ? `FRED \`${k.slice(5)}\``
  : { cm: 'CoinMetrics community API', difficulty: 'blockchain.com', feargreed: 'alternative.me', stablecoins: 'DefiLlama', ethbtc: 'Bitstamp ETH/BTC' }[k] || k;
const GRADE = { A: 'A — strong', B: 'B — medium', C: 'C — weak / folklore' };
const pipe = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');

function describe(item) {
  const b = item.build(ctx);
  const shows = [];
  if (b.events?.length) shows.push(`${b.events.length} event line${b.events.length > 1 ? 's' : ''}`);
  if (b.zones?.length) shows.push(`${b.zones.length} shaded period${b.zones.length > 1 ? 's' : ''}`);
  for (const l of b.lines || []) {
    const where = l.target === 'price' ? 'line on price' : l.target === 'overlay' ? 'line on its own scale' : 'panel below';
    shows.push(`${l.name} (${where})`);
  }
  const source = item.src || (item.needs.length ? item.needs.map(NEED_SRC).join(', ')
    : b.lines?.length ? 'Computed from BTC daily price' : 'Hand-curated dates (`public/js/events-data.js`)');
  return { b, shows: shows.join('; '), source };
}

const D = Object.fromEntries(ITEMS.map((i) => [i.id, describe(i)]));

// ── README table
let table = '';
for (const g of GROUPS) {
  const items = ITEMS.filter((i) => i.group === g.id);
  table += `\n### ${g.name}\n\n| Overlay | Evidence | What it is | Shows | Data source |\n|---|---|---|---|---|\n`;
  for (const i of items) table += `| **${pipe(i.name)}** <br><sub>\`${i.id}\`</sub> | ${i.grade} | ${pipe(i.desc)} | ${pipe(D[i.id].shows)} | ${pipe(D[i.id].source)} |\n`;
  for (const u of UNAVAILABLE.filter((x) => x.group === g.id)) table += `| ~~${pipe(u.name)}~~ | — | Not included: ${pipe(u.why)} | — | Paid / blocked |\n`;
}
const readmePath = path.join(ROOT, 'README.md');
const readme = readFileSync(readmePath, 'utf8');
const START = '<!-- overlays:start -->', END = '<!-- overlays:end -->';
const body = `${START}\n_${ITEMS.length} overlays in ${GROUPS.length} groups. Generated by \`npm run docs\`. Full dates for every overlay: [docs/OVERLAYS.md](docs/OVERLAYS.md)._\n${table}\n${END}`;
writeFileSync(readmePath, readme.replace(new RegExp(`${START}[\\s\\S]*${END}`), body));

// ── docs/OVERLAYS.md with every instance
let out = `# Crows Chart — overlay reference\n\nEvery overlay in the app, with every date it draws. Generated by \`npm run docs\` from \`public/js/catalog.js\` on ${new Date().toISOString().slice(0, 10)}.\n\nEvidence grades: ${Object.values(GRADE).join(' · ')}.\n\nCorrelation is not cause. Bitcoin has had only 4 halving cycles, so every pattern here rests on a few examples.\n`;
for (const g of GROUPS) {
  out += `\n## ${g.name}\n`;
  for (const i of ITEMS.filter((x) => x.group === g.id)) {
    const { b, shows, source } = D[i.id];
    out += `\n### ${i.name}\n\n- **id:** \`${i.id}\`\n- **Evidence:** ${GRADE[i.grade]}\n- **What it is:** ${i.desc}\n- **Shows:** ${shows || '—'}\n- **Data source:** ${source}\n`;
    if (b.info) out += `- **Model:** ${b.info}\n`;
    for (const l of b.lines || []) if (l.levels?.length) out += `- **Reference levels (${l.name}):** ${l.levels.join(', ')}\n`;
    const zones = b.zones || [], events = b.events || [];
    if (zones.length && zones.length <= 60) {
      out += '\n| Period | From | To | Note |\n|---|---|---|---|\n';
      for (const z of zones) out += `| ${pipe(z.label)} | ${z.from} | ${z.to || 'ongoing'} | ${pipe(z.note)}${z.approx ? ' (approx.)' : ''} |\n`;
    } else if (zones.length) out += `\n${zones.length} periods, ${zones[0].from} → ${zones[zones.length - 1].to || 'ongoing'} (too many to list).\n`;
    if (events.length && events.length <= 60) {
      out += '\n| Date | Event | Note |\n|---|---|---|\n';
      for (const e of events) out += `| ${e.d} | ${pipe(e.label)} | ${pipe(e.note)}${e.approx ? ' (approx.)' : ''} |\n`;
    } else if (events.length) out += `\n${events.length} dates, ${events[0].d} → ${events[events.length - 1].d} (too many to list).\n`;
  }
  const na = UNAVAILABLE.filter((x) => x.group === g.id);
  if (na.length) { out += '\n**Not included (no free data):**\n\n'; for (const u of na) out += `- ${u.name}: ${u.why}\n`; }
}
writeFileSync(path.join(ROOT, 'docs/OVERLAYS.md'), out);
console.log(`README table + docs/OVERLAYS.md written (${ITEMS.length} overlays).`);
